<script setup lang="ts">
import { computed, onMounted, watch } from 'vue'
import { useRouter } from 'vue-router'
import { ArrowLeft, FileText, GitCompare, Layers, ShieldCheck } from 'lucide-vue-next'
import Badge from '@/components/common/Badge.vue'
import DataSourceBanner from '@/components/common/DataSourceBanner.vue'
import EmptyState from '@/components/common/EmptyState.vue'
import ErrorRetry from '@/components/common/ErrorRetry.vue'
import Skeleton from '@/components/common/Skeleton.vue'
import PayoffChart from '@/components/charts/PayoffChart.vue'
import { useStrategiesStore } from '@/stores/strategies'
import { useTradeProposalsStore } from '@/stores/tradeProposals'
import { useUiNotificationsStore } from '@/stores/uiNotifications'
import { formatCurrency, formatDateTime, formatPercent, occSymbolLabel, truncateMiddle } from '@/utils/format'
import type { EvidenceSection } from '@/types/api'

const props = defineProps<{ id?: string }>()

const strategies = useStrategiesStore()
const proposals = useTradeProposalsStore()
const ui = useUiNotificationsStore()
const router = useRouter()

async function loadStrategy(id?: string): Promise<void> {
  let targetId = id
  if (!targetId) {
    if (strategies.opportunities.length === 0) await strategies.loadOpportunities()
    targetId = strategies.opportunities.find((s) => s.rank === 1)?.id ?? strategies.opportunities[0]?.id
  }
  if (targetId) await strategies.selectStrategy(targetId)
}

onMounted(() => void loadStrategy(props.id))
watch(
  () => props.id,
  (next) => void loadStrategy(next),
)

const detail = computed(() => strategies.detail)
const payoff = computed(() => strategies.payoff)

const EVIDENCE_ORDER: EvidenceSection['key'][] = [
  'market_conditions',
  'technical_signals',
  'volatility',
  'liquidity',
  'risk_analysis',
  'expected_outcome',
  'invalidation',
]

const orderedEvidence = computed(() => {
  if (!detail.value) return []
  // The backend doesn't always return `evidence` (see StrategyResource) --
  // treat it as absent rather than crashing when it's missing.
  return EVIDENCE_ORDER.map((key) => detail.value!.evidence?.find((e) => e.key === key)).filter((e): e is EvidenceSection => Boolean(e))
})

const riskRewardRatio = computed(() => {
  if (!detail.value) return null
  const risk = Number.parseFloat(detail.value.max_loss)
  const reward = Number.parseFloat(detail.value.max_profit)
  if (!risk) return null
  return reward / risk
})

async function createProposal(): Promise<void> {
  if (!detail.value) return
  if (proposals.proposals.length === 0) await proposals.loadProposals()
  const match = proposals.proposals.find((p) => p.strategy_id === detail.value!.id)
  if (match) {
    await router.push({ name: 'trade-execution', params: { proposalId: match.id } })
  } else {
    ui.info('No trade proposal exists yet for this strategy — proposals are generated by the agent pipeline during a run.')
  }
}

function compareStrategy(): void {
  ui.info('Side-by-side comparison is not available in this build yet.')
}
</script>

<template>
  <div class="space-y-5">
    <DataSourceBanner :reason="ui.fallbackDomains['strategy-detail'] ?? null" />

    <div class="flex flex-wrap items-center justify-between gap-2">
      <button type="button" class="inline-flex items-center gap-1.5 text-sm font-medium text-slate-600 hover:text-ink-950" @click="router.push('/options-scanner')">
        <ArrowLeft :size="15" />
        Return to Scanner
      </button>
      <div class="flex items-center gap-3">
        <button
          type="button"
          class="inline-flex items-center gap-1.5 rounded-control border border-border bg-surface px-3 py-1.5 text-sm font-medium text-ink-950 opacity-50 cursor-not-allowed hover:bg-surface"
          title="Side-by-side comparison is not available in this build yet."
          @click="compareStrategy"
        >
          <GitCompare :size="14" />
          Compare
        </button>
        <button type="button" class="inline-flex items-center gap-1.5 rounded-control bg-brand-600 px-3 py-1.5 text-sm font-medium text-white hover:bg-brand-700" @click="createProposal">
          <FileText :size="14" />
          View Trade Proposal
        </button>
      </div>
    </div>

    <div v-if="strategies.isLoadingDetail && !detail" class="space-y-3">
      <Skeleton height="4rem" />
      <Skeleton height="20rem" />
    </div>
    <ErrorRetry v-else-if="strategies.detailError" :message="strategies.detailError" @retry="() => loadStrategy(props.id)" />
    <EmptyState v-else-if="!detail" title="No strategy selected" description="Pick a strategy from the Options Scanner." />

    <template v-else>
      <div class="rounded-card border border-border bg-surface p-4 shadow-sm">
        <div class="flex flex-wrap items-center justify-between gap-2">
          <div>
            <div class="flex items-center gap-2">
              <h2 class="text-lg font-semibold text-ink-950">{{ detail.symbol }}</h2>
              <Badge tone="info" class="capitalize">{{ detail.strategy_type?.replaceAll('_', ' ') ?? '--' }}</Badge>
              <Badge :tone="detail.selected ? 'success' : 'neutral'">{{ detail.selected ? 'selected' : `rank ${detail.rank ?? '--'}` }}</Badge>
            </div>
            <p class="mt-1 text-xs text-slate-600">Quote as of {{ formatDateTime(detail.quote_timestamp) }} · {{ detail.dte }} DTE</p>
          </div>
          <div class="text-right">
            <p class="text-xs text-slate-600">Confidence</p>
            <p class="tabular-nums text-xl font-semibold text-brand-700">{{ formatPercent(detail.confidence) }}</p>
          </div>
        </div>
        <p class="mt-3 text-sm text-slate-600">{{ detail.thesis }}</p>
      </div>

      <div class="grid grid-cols-1 gap-5 xl:grid-cols-3">
        <div class="space-y-5 xl:col-span-2">
          <div class="rounded-card border border-border bg-surface p-4 shadow-sm">
            <h2 class="mb-2 text-sm font-semibold text-ink-950">Payoff Diagram</h2>
            <PayoffChart v-if="payoff" :curve="payoff" />
            <Skeleton v-else height="320px" />
          </div>

          <div class="rounded-card border border-border bg-surface p-4 shadow-sm">
            <h2 class="mb-3 flex items-center gap-1.5 text-sm font-semibold text-ink-950"><Layers :size="15" /> Legs</h2>
            <div class="scroll-x">
              <table class="w-full min-w-[640px] text-sm">
                <thead>
                  <tr class="border-b border-border text-left text-xs text-slate-600">
                    <th class="py-2 font-medium">Action</th>
                    <th class="py-2 font-medium">Contract</th>
                    <th class="py-2 font-medium">Strike</th>
                    <th class="py-2 font-medium">Bid/Ask</th>
                    <th class="py-2 font-medium">Delta</th>
                    <th class="py-2 font-medium">OI / Vol</th>
                  </tr>
                </thead>
                <tbody>
                  <tr v-for="leg in detail.legs" :key="leg.id" class="border-b border-border last:border-0">
                    <td class="py-2">
                      <Badge :tone="leg.action === 'buy' ? 'success' : 'danger'" class="capitalize">{{ leg.action }}</Badge>
                    </td>
                    <td class="py-2 text-ink-950" :title="leg.occ_symbol">{{ truncateMiddle(occSymbolLabel(leg.occ_symbol), 30) }}</td>
                    <td class="tabular-nums py-2">{{ formatCurrency(leg.strike) }}</td>
                    <td class="tabular-nums py-2">{{ formatCurrency(leg.quote_bid) }} / {{ formatCurrency(leg.quote_ask) }}</td>
                    <td class="tabular-nums py-2">{{ leg.delta ?? '--' }}</td>
                    <td class="tabular-nums py-2">{{ leg.open_interest ?? '--' }} / {{ leg.volume ?? '--' }}</td>
                  </tr>
                </tbody>
              </table>
            </div>
          </div>

          <div class="rounded-card border border-border bg-surface p-4 shadow-sm">
            <h2 class="mb-3 text-sm font-semibold text-ink-950">AI Explanation</h2>
            <div class="space-y-4">
              <section v-for="section in orderedEvidence" :key="section.key">
                <h3 class="text-sm font-semibold text-ink-950">{{ section.title }}</h3>
                <p class="mt-1 text-sm text-slate-600">{{ section.body }}</p>
                <ul v-if="section.bullets" class="mt-1.5 list-inside list-disc space-y-0.5 text-sm text-slate-600">
                  <li v-for="(bullet, i) in section.bullets" :key="i">{{ bullet }}</li>
                </ul>
                <p class="mt-1 text-[11px] text-slate-600">Evidence as of {{ formatDateTime(detail.quote_timestamp) }}</p>
              </section>
            </div>
          </div>
        </div>

        <div class="space-y-5">
          <div class="rounded-card border border-border bg-surface p-4 shadow-sm">
            <h2 class="mb-3 text-sm font-semibold text-ink-950">Key Figures</h2>
            <dl class="grid grid-cols-2 gap-3 text-sm">
              <div>
                <dt class="text-xs text-slate-600">Net {{ detail.net_debit ? 'debit' : 'credit' }}</dt>
                <dd class="tabular-nums font-semibold text-ink-950">{{ formatCurrency(detail.net_debit ?? detail.net_credit) }}</dd>
              </div>
              <div>
                <dt class="text-xs text-slate-600">Max profit</dt>
                <dd class="tabular-nums font-semibold text-success">{{ formatCurrency(detail.max_profit) }}</dd>
              </div>
              <div>
                <dt class="text-xs text-slate-600">Max loss</dt>
                <dd class="tabular-nums font-semibold text-danger">-{{ formatCurrency(detail.max_loss) }}</dd>
              </div>
              <div>
                <dt class="text-xs text-slate-600">Risk/reward</dt>
                <dd class="tabular-nums font-semibold text-ink-950">{{ riskRewardRatio ? `1 : ${riskRewardRatio.toFixed(2)}` : '--' }}</dd>
              </div>
              <div>
                <dt class="text-xs text-slate-600">Probability of profit</dt>
                <dd class="tabular-nums font-semibold text-ink-950">{{ formatPercent(detail.probability_of_profit) }}</dd>
              </div>
              <div>
                <dt class="text-xs text-slate-600">Liquidity score</dt>
                <dd class="tabular-nums font-semibold text-ink-950">{{ formatPercent(detail.liquidity_score) }}</dd>
              </div>
              <div>
                <dt class="text-xs text-slate-600">DTE</dt>
                <dd class="tabular-nums font-semibold text-ink-950">{{ detail.dte }}</dd>
              </div>
              <div>
                <dt class="text-xs text-slate-600">Regime</dt>
                <dd class="font-semibold capitalize text-ink-950">{{ detail.regime }}</dd>
              </div>
            </dl>
          </div>

          <div class="rounded-card border border-border bg-surface p-4 shadow-sm">
            <h2 class="mb-3 text-sm font-semibold text-ink-950">Confidence Breakdown</h2>
            <p class="mb-2 text-xs font-medium uppercase tracking-wide text-slate-600">Deterministic</p>
            <ul class="mb-3 space-y-1.5">
              <li v-for="c in detail.score_breakdown.deterministic" :key="c.label" class="flex items-center justify-between text-xs">
                <span class="text-slate-600">{{ c.label }} <span class="text-slate-600/70">(w {{ c.weight }})</span></span>
                <span class="tabular-nums font-medium text-ink-950">{{ formatPercent(c.value) }}</span>
              </li>
            </ul>
            <p class="mb-2 text-xs font-medium uppercase tracking-wide text-slate-600">Model judgment</p>
            <ul class="space-y-1.5">
              <li v-for="c in detail.score_breakdown.model_judgment" :key="c.label" class="flex items-center justify-between text-xs">
                <span class="text-slate-600">{{ c.label }} <span class="text-slate-600/70">(w {{ c.weight }})</span></span>
                <span class="tabular-nums font-medium text-ink-950">{{ formatPercent(c.value) }}</span>
              </li>
            </ul>
            <div class="mt-3 flex items-center justify-between border-t border-border pt-2 text-sm font-semibold">
              <span class="text-ink-950">Total score</span>
              <span class="tabular-nums text-brand-700">{{ formatPercent(detail.score_breakdown.total) }}</span>
            </div>
          </div>

          <div class="rounded-card border border-border bg-canvas p-4">
            <h2 class="mb-2 flex items-center gap-1.5 text-xs font-semibold uppercase tracking-wide text-slate-600"><ShieldCheck :size="13" /> Audit ribbon</h2>
            <dl class="space-y-1 text-xs">
              <div class="flex justify-between gap-2"><dt class="text-slate-600">Run ID</dt><dd class="truncate font-medium text-ink-950">{{ detail.audit?.run_id ?? '--' }}</dd></div>
              <div class="flex justify-between gap-2"><dt class="text-slate-600">Prompt version</dt><dd class="font-medium text-ink-950">{{ detail.audit?.prompt_version ?? '--' }}</dd></div>
              <div class="flex justify-between gap-2"><dt class="text-slate-600">Model</dt><dd class="font-medium text-ink-950">{{ detail.audit?.model_provider ?? '--' }} / {{ detail.audit?.model_name ?? '--' }}</dd></div>
              <div class="flex justify-between gap-2"><dt class="text-slate-600">Risk policy</dt><dd class="font-medium text-ink-950">v{{ detail.audit?.risk_policy_version ?? '--' }}</dd></div>
              <div><dt class="text-slate-600">Tools used</dt><dd class="mt-0.5 flex flex-wrap gap-1"><Badge v-for="tool in detail.audit?.tools_used ?? []" :key="tool" tone="neutral">{{ tool }}</Badge></dd></div>
            </dl>
            <router-link v-if="detail.audit?.trace_url" :to="detail.audit.trace_url" class="mt-2 inline-block text-xs font-medium text-brand-700 hover:underline">View full trace →</router-link>
          </div>
        </div>
      </div>
    </template>
  </div>
</template>
